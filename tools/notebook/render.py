"""INDEX.md, SHEETS.md, TAGS.md and the README numbers block."""
import importlib
import json
import os
import re
import sys
from pathlib import Path
from urllib.parse import quote

from notebook.model import DIFFICULTIES, REPO, taxonomy

SHEETS_FILE = REPO / "tools" / "sheets.json"
STATS_START, STATS_END = "<!-- generated:stats -->", "<!-- /generated:stats -->"
SHEET_SHORT = {"NeetCode 150": "N150", "LeetCode Top Interview 150": "TI150",
               "Striver A2Z DSA Sheet (LeetCode problems)": "A2Z", "Grind 169": "G169", "LeetCode 75": "LC75"}


def link_to(note, from_dir=REPO):
    return quote(Path(os.path.relpath(note.path, from_dir)).as_posix(), safe="/._-")


def row(note, link, *extra):
    cells = [str(note.number), f"[{note.title}]({link})", note.difficulty, *extra, note.status]
    return "| " + " | ".join(cells) + " |"


def sheets():
    return json.loads(SHEETS_FILE.read_text(encoding="utf-8"))


def sheet_membership():
    """{number: ["N150", "G169", …]} for every problem on a sheet."""
    out = {}
    for name, sheet in sheets().items():
        for topic in sheet["topics"]:
            for num in topic["problems"]:
                out.setdefault(num, []).append(SHEET_SHORT.get(name, name))
    return out


def by_folder(notes):
    order = list(taxonomy()["folders"])
    groups = {}
    for note in notes:
        groups.setdefault(note.folder, []).append(note)
    return [(f, sorted(groups[f], key=lambda n: n.number)) for f in sorted(groups, key=order.index)]


def render_index(notes):
    counts = {d: sum(1 for n in notes if n.difficulty == d) for d in DIFFICULTIES}
    solved = sum(1 for n in notes if n.status == "✅")
    lines = [
        "# Index", "", "Generated by `python tools/build_index.py`; do not edit by hand.", "",
        f"**{len(notes)} problems** · Easy {counts['Easy']} · Medium {counts['Medium']} · Hard {counts['Hard']}"
        f" · ✅ solved {solved} · 🔄 to review {len(notes) - solved}", "",
        "Each folder heading links to its pattern page (problems easiest first). Other views: by sheet → "
        "[SHEETS.md](SHEETS.md) · by tag (a problem can have several) → [TAGS.md](TAGS.md) · by company → "
        "[COMPANIES.md](COMPANIES.md) · exam practice → [Infosys_SP_DSE](Infosys_SP_DSE/README.md)", "",
    ]
    folders = taxonomy()["folders"]
    for folder, group in by_folder(notes):
        lines += [f"## [{folders[folder]['title']}]({folder}/README.md)", "",
                  "| # | Problem | Difficulty | Tags | Status |", "|---|---|---|---|---|"]
        lines += [row(n, link_to(n), ", ".join(n.tags)) for n in group]
        lines.append("")
    return "\n".join(lines).rstrip("\n") + "\n"


def render_sheets(notes):
    """SHEETS.md: every problem of each famous sheet (tools/sheets.json), linked to its note."""
    by_number = {n.number: n for n in notes}
    lines = ["# Problem Sheets", "",
             "Generated by `python tools/build_index.py` from `tools/sheets.json`; do not edit by hand.", ""]
    data = sheets()
    for name, sheet in data.items():
        numbers = {num for topic in sheet["topics"] for num in topic["problems"]}
        present = [by_number[num] for num in numbers if num in by_number]
        solved = sum(1 for n in present if n.status == "✅")
        anchor = re.sub(r"[^a-z0-9 -]", "", name.lower()).replace(" ", "-")
        lines.append(f"* [{name}](#{anchor}): {len(present)}/{len(numbers)} in this repo · ✅ {solved}")
    for name, sheet in data.items():
        lines += ["", f"## {name}", "", f"Source: {sheet['source']}", ""]
        for topic in sheet["topics"]:
            lines += [f"### {topic['topic']}", "", "| # | Problem | Difficulty | Status |", "|---|---|---|---|"]
            for num in topic["problems"]:
                note = by_number.get(num)
                lines.append(row(note, link_to(note)) if note else f"| {num} | *not in this repo yet* | — | — |")
            lines.append("")
    return "\n".join(lines).rstrip("\n") + "\n"


def render_tags(notes):
    """TAGS.md: every tag with all its problems, whatever folder they live in."""
    labels = taxonomy()["tags"]
    used = {t for n in notes for t in n.tags}
    lines = ["# Tags", "", "Generated by `python tools/build_index.py`; do not edit by hand. A problem lives in one "
             "folder but can carry up to four tags, so this is where to find, say, every monotonic-stack problem.", ""]
    lines.append(" · ".join(f"[{t}](#{t})" for t in labels if t in used))
    for tag in labels:
        group = sorted((n for n in notes if tag in n.tags), key=lambda n: (DIFFICULTIES.index(n.difficulty), n.number))
        if not group:
            continue
        lines += ["", f"## {tag}", "", f"{labels[tag]} · {len(group)} problems", "",
                  "| # | Problem | Difficulty | Folder | Status |", "|---|---|---|---|---|"]
        lines += [row(n, link_to(n), n.folder.replace("_", " ")) for n in group]
    return "\n".join(lines) + "\n"


def check_count():
    """Number of registered checks in tools/verify (imports the test modules; ~0.3 s)."""
    verify = REPO / "tools" / "verify"
    if str(verify) not in sys.path:
        sys.path.insert(0, str(verify))
    harness = importlib.import_module("harness")
    for f in sorted(verify.glob("tests_*.py")):
        importlib.import_module(f.stem)
    return len(harness.CASES)


def render_stats(notes):
    """The README's numbers table, so they can never drift from the repo."""
    counts = {d: sum(1 for n in notes if n.difficulty == d) for d in DIFFICULTIES}
    solved = sum(1 for n in notes if n.status == "✅")
    folders = len({n.folder for n in notes})
    numbers_here = {n.number for n in notes}
    coverage = []
    for name, sheet in sheets().items():
        numbers = {num for topic in sheet["topics"] for num in topic["problems"]}
        coverage.append(f"{name} {len(numbers & numbers_here)}/{len(numbers)}")
    mocks = sorted((REPO / "Infosys_SP_DSE").glob("Mock_Test_*/Q*.md"))
    tests = len({p.parent for p in mocks})
    return "\n".join([
        STATS_START, "| | |", "|---|---|",
        f"| **LeetCode notes** | **{len(notes)}** (Easy {counts['Easy']} · Medium {counts['Medium']} · Hard "
        f"{counts['Hard']}) in {folders} pattern folders · ✅ {solved} · 🔄 {len(notes) - solved} → [INDEX.md](INDEX.md) |",
        f"| **Sheets** | {' · '.join(coverage)} → [SHEETS.md](SHEETS.md) |",
        f"| **Infosys mock problems** | {len(mocks)} original stdin/stdout problems ({tests} mock tests) with an "
        "offline judge → [Infosys_SP_DSE](Infosys_SP_DSE/README.md) |",
        f"| **Checks** | {check_count()} automated checks, run in CI on every push, every pull request and weekly |",
        STATS_END,
    ])


def with_block(text, start, end, block, name):
    i, j = text.find(start), text.find(end)
    if i == -1 or j == -1:
        sys.exit(f"{name} must contain {start} … {end}")
    return text[:i] + block + text[j + len(end):]
