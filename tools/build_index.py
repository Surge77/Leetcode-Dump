"""Generate INDEX.md, SHEETS.md and the README's numbers, and enforce the note format.

    python tools/build_index.py           # check note format, rewrite the generated files
    python tools/build_index.py --check   # exit 1 on a format error or a stale generated file (CI, pre-commit)

Every LeetCode note must start with

    # 🔹 Problem Name: <number>. <Title> (<Category>, <Easy|Medium|Hard>)

and contain exactly one `**🟢 Status:** ✅ Solved` or `**🟢 Status:** 🔄 Need Review`
line and a `**🔗 Link:**` line pointing at leetcode.com/problems/.
"""
import importlib
import json
import re
import sys
from dataclasses import dataclass
from pathlib import Path
from urllib.parse import quote

REPO = Path(__file__).resolve().parents[1]
SKIP_DIRS = {"LeetcodeTemplates", "Infosys_SP_DSE", "Interview_Prep", "tools", ".github", ".githooks"}
HEADER_RE = re.compile(r"^# 🔹 Problem Name: (\d+)\. (.+) \(([^()]+), (Easy|Medium|Hard)\)$")
STATUS_RE = re.compile(r"^\*\*🟢 Status:\*\* (.*)$", re.M)
LINK_RE = re.compile(r"^\*\*🔗 Link:\*\* .*https://leetcode\.com/problems/", re.M)
SHEETS_FILE = REPO / "tools" / "sheets.json"
README = REPO / "README.md"
STATS_START, STATS_END = "<!-- generated:stats -->", "<!-- /generated:stats -->"
STATUSES = {"✅ Solved": "✅", "🔄 Need Review": "🔄"}
DIFFICULTIES = ("Easy", "Medium", "Hard")


@dataclass(frozen=True)
class Note:
    path: Path
    number: int
    title: str
    difficulty: str
    status: str  # "✅" or "🔄"


def note_paths():
    return sorted(p for p in REPO.rglob("*.md")
                  if p.parent != REPO and p.relative_to(REPO).parts[0] not in SKIP_DIRS
                  and ".git" not in p.parts and re.match(r"\d+\.", p.name))


def parse(path):
    """Return (Note, []) for a well-formed note, or (None, [errors])."""
    text = path.read_text(encoding="utf-8").replace("\r\n", "\n")
    rel = path.relative_to(REPO).as_posix()
    errors = []
    first = text.split("\n", 1)[0]
    header = HEADER_RE.match(first)
    file_number = int(path.name.split(".", 1)[0])
    if not header:
        errors.append(f"{rel}: first line must be '# 🔹 Problem Name: N. Title (Category, Difficulty)', got {first!r}")
    elif int(header.group(1)) != file_number:
        errors.append(f"{rel}: header number {header.group(1)} != file number {file_number}")
    statuses = STATUS_RE.findall(text)
    if len(statuses) != 1 or statuses[0].strip() not in STATUSES:
        errors.append(f"{rel}: need exactly one status line, one of {list(STATUSES)}; found {statuses}")
    if not LINK_RE.search(text):
        errors.append(f"{rel}: missing '**🔗 Link:**' line with a leetcode.com/problems/ URL")
    if errors or header is None:
        return None, errors
    return Note(path, file_number, header.group(2).strip(), header.group(4), STATUSES[statuses[0].strip()]), []


def load_notes():
    notes, errors = [], []
    for path in note_paths():
        note, problems = parse(path)
        errors += problems
        if note:
            notes.append(note)
    return notes, errors


def render(notes):
    counts = {d: sum(1 for n in notes if n.difficulty == d) for d in DIFFICULTIES}
    solved = sum(1 for n in notes if n.status == "✅")
    lines = [
        "# Index",
        "",
        "Generated by `python tools/build_index.py` — do not edit by hand.",
        "",
        f"**{len(notes)} problems** · Easy {counts['Easy']} · Medium {counts['Medium']} · Hard {counts['Hard']}"
        f" · ✅ solved {solved} · 🔄 to review {len(notes) - solved}",
        "",
        "Exam-structured practice (mock tests, judge, contest template): [Infosys_SP_DSE](Infosys_SP_DSE/README.md)",
        "",
        "By sheet (NeetCode 150, Top Interview 150, Striver A2Z): [SHEETS.md](SHEETS.md)",
        "",
    ]
    by_folder = {}
    for note in notes:
        by_folder.setdefault(note.path.relative_to(REPO).parts[0], []).append(note)
    for folder in sorted(by_folder, key=str.lower):
        lines += [f"## {folder.replace('_', ' ')}", "", "| # | Problem | Difficulty | Status |", "|---|---|---|---|"]
        for note in sorted(by_folder[folder], key=lambda n: n.number):
            link = quote(note.path.relative_to(REPO).as_posix())
            lines.append(f"| {note.number} | [{note.title}]({link}) | {note.difficulty} | {note.status} |")
        lines.append("")
    return "\n".join(lines)


def render_sheets(notes):
    """SHEETS.md: every problem of each famous sheet (tools/sheets.json), linked to its note."""
    by_number = {n.number: n for n in notes}
    sheets = json.loads(SHEETS_FILE.read_text(encoding="utf-8"))
    lines = ["# Problem Sheets", "", "Generated by `python tools/build_index.py` from `tools/sheets.json` — do not edit by hand.", ""]
    for name, sheet in sheets.items():
        numbers = {num for topic in sheet["topics"] for num in topic["problems"]}
        present = [by_number[num] for num in numbers if num in by_number]
        solved = sum(1 for n in present if n.status == "✅")
        anchor = re.sub(r"[^a-z0-9 -]", "", name.lower()).replace(" ", "-")
        lines.append(f"* [{name}](#{anchor}) — {len(present)}/{len(numbers)} in this repo · ✅ {solved}")
    for name, sheet in sheets.items():
        lines += ["", f"## {name}", "", f"Source: {sheet['source']}", ""]
        for topic in sheet["topics"]:
            lines += [f"### {topic['topic']}", "", "| # | Problem | Difficulty | Status |", "|---|---|---|---|"]
            for num in topic["problems"]:
                note = by_number.get(num)
                if note is None:
                    lines.append(f"| {num} | *not in this repo yet* | — | — |")
                    continue
                link = quote(note.path.relative_to(REPO).as_posix())
                lines.append(f"| {num} | [{note.title}]({link}) | {note.difficulty} | {note.status} |")
            lines.append("")
    return "\n".join(lines).rstrip("\n") + "\n"


def check_count():
    """Number of registered checks in tools/verify (imports the test modules; ~0.3 s)."""
    verify = REPO / "tools" / "verify"
    if str(verify) not in sys.path:
        sys.path.insert(0, str(verify))
    harness = importlib.import_module("harness")
    for f in sorted(verify.glob("tests_*.py")):
        importlib.import_module(f.stem)
    return len(harness.CASES)


def render_stats(notes):
    """The README's numbers table, so they can never drift from the repo."""
    counts = {d: sum(1 for n in notes if n.difficulty == d) for d in DIFFICULTIES}
    solved = sum(1 for n in notes if n.status == "✅")
    folders = len({n.path.relative_to(REPO).parts[0] for n in notes})
    by_number = {n.number for n in notes}
    sheets = json.loads(SHEETS_FILE.read_text(encoding="utf-8"))
    coverage = []
    for name, sheet in sheets.items():
        numbers = {num for topic in sheet["topics"] for num in topic["problems"]}
        coverage.append(f"{name} {len(numbers & by_number)}/{len(numbers)}")
    mocks = sorted((REPO / "Infosys_SP_DSE").glob("Mock_Test_*/Q*.md"))
    tests = len({p.parent for p in mocks})
    return "\n".join([
        STATS_START,
        "| | |",
        "|---|---|",
        f"| **LeetCode notes** | **{len(notes)}** (Easy {counts['Easy']} · Medium {counts['Medium']} · Hard "
        f"{counts['Hard']}) in {folders} pattern folders · ✅ {solved} · 🔄 {len(notes) - solved} → [INDEX.md](INDEX.md) |",
        f"| **Sheets** | {' · '.join(coverage)} → [SHEETS.md](SHEETS.md) |",
        f"| **Infosys mock problems** | {len(mocks)} original stdin/stdout problems ({tests} mock tests) with an "
        "offline judge → [Infosys_SP_DSE](Infosys_SP_DSE/README.md) |",
        f"| **Checks** | {check_count()} automated checks, run in CI on every push, every pull request and weekly |",
        STATS_END,
    ])


def with_stats(readme, notes):
    start, end = readme.find(STATS_START), readme.find(STATS_END)
    if start == -1 or end == -1:
        sys.exit(f"README.md must contain {STATS_START} … {STATS_END}")
    return readme[:start] + render_stats(notes) + readme[end + len(STATS_END):]


def checked_notes():
    """All notes, or SystemExit listing every format error."""
    notes, errors = load_notes()
    if errors:
        sys.exit("Note format errors:\n  " + "\n  ".join(errors))
    return notes


def generated(notes):
    """{output file: expected content} for every generated document."""
    readme = README.read_text(encoding="utf-8").replace("\r\n", "\n")
    return {REPO / "INDEX.md": render(notes), REPO / "SHEETS.md": render_sheets(notes),
            README: with_stats(readme, notes)}


def write_index():
    """Rewrite INDEX.md and SHEETS.md; return the number of notes."""
    notes = checked_notes()
    for target, content in generated(notes).items():
        target.write_text(content, encoding="utf-8", newline="\n")
    return len(notes)


def main():
    if "--check" not in sys.argv:
        print(f"{write_index()} notes well-formed; wrote INDEX.md, SHEETS.md and the README numbers")
        return
    notes = checked_notes()
    for target, content in generated(notes).items():
        current = target.read_text(encoding="utf-8") if target.exists() else ""
        if current.replace("\r\n", "\n") != content:
            sys.exit(f"{target.name} is stale: run `python tools/build_index.py`")
    print(f"{len(notes)} notes well-formed; INDEX.md, SHEETS.md and the README numbers are up to date")


if __name__ == "__main__":
    main()
