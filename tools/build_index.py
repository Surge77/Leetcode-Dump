"""Generate INDEX.md and enforce the note format.

    python tools/build_index.py           # check note format, rewrite INDEX.md
    python tools/build_index.py --check   # exit 1 on a format error or a stale INDEX.md (CI, pre-commit)

Every LeetCode note must start with

    # 🔹 Problem Name: <number>. <Title> (<Category>, <Easy|Medium|Hard>)

and contain exactly one `**🟢 Status:** ✅ Solved` or `**🟢 Status:** 🔄 Need Review`
line and a `**🔗 Link:**` line pointing at leetcode.com/problems/.
"""
import re
import sys
from dataclasses import dataclass
from pathlib import Path
from urllib.parse import quote

REPO = Path(__file__).resolve().parents[1]
SKIP_DIRS = {"LeetcodeTemplates", "Infosys_SP_DSE", "Interview_Prep", "tools", ".github", ".githooks"}
HEADER_RE = re.compile(r"^# 🔹 Problem Name: (\d+)\. (.+) \(([^()]+), (Easy|Medium|Hard)\)$")
STATUS_RE = re.compile(r"^\*\*🟢 Status:\*\* (.*)$", re.M)
LINK_RE = re.compile(r"^\*\*🔗 Link:\*\* .*https://leetcode\.com/problems/", re.M)
STATUSES = {"✅ Solved": "✅", "🔄 Need Review": "🔄"}
DIFFICULTIES = ("Easy", "Medium", "Hard")


@dataclass(frozen=True)
class Note:
    path: Path
    number: int
    title: str
    difficulty: str
    status: str  # "✅" or "🔄"


def note_paths():
    return sorted(p for p in REPO.rglob("*.md")
                  if p.parent != REPO and p.relative_to(REPO).parts[0] not in SKIP_DIRS
                  and ".git" not in p.parts and re.match(r"\d+\.", p.name))


def parse(path):
    """Return (Note, []) for a well-formed note, or (None, [errors])."""
    text = path.read_text(encoding="utf-8").replace("\r\n", "\n")
    rel = path.relative_to(REPO).as_posix()
    errors = []
    first = text.split("\n", 1)[0]
    header = HEADER_RE.match(first)
    file_number = int(path.name.split(".", 1)[0])
    if not header:
        errors.append(f"{rel}: first line must be '# 🔹 Problem Name: N. Title (Category, Difficulty)', got {first!r}")
    elif int(header.group(1)) != file_number:
        errors.append(f"{rel}: header number {header.group(1)} != file number {file_number}")
    statuses = STATUS_RE.findall(text)
    if len(statuses) != 1 or statuses[0].strip() not in STATUSES:
        errors.append(f"{rel}: need exactly one status line, one of {list(STATUSES)}; found {statuses}")
    if not LINK_RE.search(text):
        errors.append(f"{rel}: missing '**🔗 Link:**' line with a leetcode.com/problems/ URL")
    if errors or header is None:
        return None, errors
    return Note(path, file_number, header.group(2).strip(), header.group(4), STATUSES[statuses[0].strip()]), []


def load_notes():
    notes, errors = [], []
    for path in note_paths():
        note, problems = parse(path)
        errors += problems
        if note:
            notes.append(note)
    return notes, errors


def render(notes):
    counts = {d: sum(1 for n in notes if n.difficulty == d) for d in DIFFICULTIES}
    solved = sum(1 for n in notes if n.status == "✅")
    lines = [
        "# Index",
        "",
        "Generated by `python tools/build_index.py` — do not edit by hand.",
        "",
        f"**{len(notes)} problems** · Easy {counts['Easy']} · Medium {counts['Medium']} · Hard {counts['Hard']}"
        f" · ✅ solved {solved} · 🔄 to review {len(notes) - solved}",
        "",
        "Exam-structured practice (mock tests, judge, contest template): [Infosys_SP_DSE](Infosys_SP_DSE/README.md)",
        "",
    ]
    by_folder = {}
    for note in notes:
        by_folder.setdefault(note.path.relative_to(REPO).parts[0], []).append(note)
    for folder in sorted(by_folder, key=str.lower):
        lines += [f"## {folder.replace('_', ' ')}", "", "| # | Problem | Difficulty | Status |", "|---|---|---|---|"]
        for note in sorted(by_folder[folder], key=lambda n: n.number):
            link = quote(note.path.relative_to(REPO).as_posix())
            lines.append(f"| {note.number} | [{note.title}]({link}) | {note.difficulty} | {note.status} |")
        lines.append("")
    return "\n".join(lines)


def checked_notes():
    """All notes, or SystemExit listing every format error."""
    notes, errors = load_notes()
    if errors:
        sys.exit("Note format errors:\n  " + "\n  ".join(errors))
    return notes


def write_index():
    """Rewrite INDEX.md; return the number of notes."""
    notes = checked_notes()
    (REPO / "INDEX.md").write_text(render(notes), encoding="utf-8", newline="\n")
    return len(notes)


def main():
    if "--check" not in sys.argv:
        print(f"{write_index()} notes well-formed; wrote INDEX.md")
        return
    notes = checked_notes()
    target = REPO / "INDEX.md"
    current = target.read_text(encoding="utf-8") if target.exists() else ""
    if current.replace("\r\n", "\n") != render(notes):
        sys.exit("INDEX.md is stale: run `python tools/build_index.py`")
    print(f"{len(notes)} notes well-formed; INDEX.md is up to date")


if __name__ == "__main__":
    main()
