"""Generate INDEX.md: every problem note, grouped by folder.

    python tools/build_index.py           # rewrite INDEX.md
    python tools/build_index.py --check   # exit 1 if INDEX.md is stale (used in CI)
"""
import re
import sys
from pathlib import Path
from urllib.parse import quote

REPO = Path(__file__).resolve().parents[1]
SKIP_DIRS = {"LeetcodeTemplates", "Infosys_SP_DSE", "tools", ".github"}
HEADER_RE = re.compile(r"Problem Name:\s*(?:\d+\.\s*)?(.+?)\s*\(([^()]*)\)\s*$")
DIFFICULTY_RE = re.compile(r"\b(Easy|Medium|Hard)\b")


def describe(path):
    text = path.read_text(encoding="utf-8")
    first = text.lstrip().splitlines()[0] if text.strip() else ""
    number = int(path.name.split(".", 1)[0])
    title = path.stem.split(".", 1)[1].replace("_", " ")
    difficulty = "—"
    match = HEADER_RE.search(first)
    if match:
        title = match.group(1).strip("* ")
        found = DIFFICULTY_RE.findall(match.group(2))
        difficulty = found[-1] if found else difficulty
    if difficulty == "—":
        found = DIFFICULTY_RE.search(text[:600])
        difficulty = found.group(1) if found else difficulty
    status_line = re.search(r"Status:\*\*(.*)", text)
    status_text = status_line.group(1) if status_line else ""
    status = "🔄" if "Need Review" in status_text else "✅" if "Solved" in status_text else "—"
    return number, title, difficulty, status


def build():
    notes = sorted(p for p in REPO.rglob("*.md")
                   if p.parent != REPO and p.parts[len(REPO.parts)] not in SKIP_DIRS
                   and ".git" not in p.parts and re.match(r"\d+\.", p.name))
    by_folder = {}
    for p in notes:
        by_folder.setdefault(p.relative_to(REPO).parts[0], []).append(p)

    rows = [describe(p) for p in notes]
    count = Counter_like(r[2] for r in rows)
    solved = sum(1 for r in rows if r[3] == "✅")
    lines = [
        "# Index",
        "",
        "Generated by `python tools/build_index.py` — do not edit by hand.",
        "",
        f"**{len(rows)} problems** · Easy {count['Easy']} · Medium {count['Medium']} · Hard {count['Hard']}"
        f" · ✅ solved {solved} · 🔄 to review {len(rows) - solved}",
        "",
        "Exam-structured practice (mock tests, contest template): [Infosys_SP_DSE](Infosys_SP_DSE/README.md)",
        "",
    ]
    for folder in sorted(by_folder, key=str.lower):
        lines += [f"## {folder.replace('_', ' ')}", "", "| # | Problem | Difficulty | Status |", "|---|---|---|---|"]
        for p in sorted(by_folder[folder], key=lambda q: int(q.name.split(".", 1)[0])):
            number, title, difficulty, status = describe(p)
            link = quote(p.relative_to(REPO).as_posix())
            lines.append(f"| {number} | [{title}]({link}) | {difficulty} | {status} |")
        lines.append("")
    return "\n".join(lines)


def Counter_like(items):
    counts = {"Easy": 0, "Medium": 0, "Hard": 0}
    for item in items:
        if item in counts:
            counts[item] += 1
    return counts


def main():
    target = REPO / "INDEX.md"
    content = build()
    if "--check" in sys.argv:
        current = target.read_text(encoding="utf-8") if target.exists() else ""
        if current.replace("\r\n", "\n") != content:
            sys.exit("INDEX.md is stale: run `python tools/build_index.py`")
        print("INDEX.md is up to date")
        return
    target.write_text(content, encoding="utf-8", newline="\n")
    print(f"wrote {target.name}")


if __name__ == "__main__":
    main()
