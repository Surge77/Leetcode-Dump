"""Pattern pages (one README.md per folder) and COMPANIES.md.

A pattern page's prose is hand-written; only the block between the ladder markers is generated: the folder's
problems easiest first, then problems from other folders that carry one of this pattern's tags.
"""
import json

from notebook.model import DIFFICULTIES, REPO, taxonomy
from notebook.render import link_to, row, sheet_membership

LADDER_START, LADDER_END = "<!-- generated:ladder -->", "<!-- /generated:ladder -->"
COMPANIES_FILE = REPO / "tools" / "companies.json"
COMPANY_TOP = 30  # problems listed per company in COMPANIES.md


def ease(note):
    return DIFFICULTIES.index(note.difficulty), note.number


def ladder(folder, notes):
    spec = taxonomy()["folders"][folder]
    here = sorted((n for n in notes if n.folder == folder), key=ease)
    elsewhere = sorted((n for n in notes if n.folder != folder and set(n.tags) & set(spec["tags_any"])), key=ease)
    sheets = sheet_membership()
    page_dir = REPO / folder
    counts = " · ".join(f"{d} {sum(1 for n in here if n.difficulty == d)}" for d in DIFFICULTIES)
    lines = [LADDER_START, "", f"### Problems, easiest first ({len(here)}: {counts})", "",
             "Generated by `python tools/build_index.py`. Sheets: N150 NeetCode 150 · TI150 Top Interview 150 · "
             "A2Z Striver · G169 Grind 169 · LC75 LeetCode 75.", "",
             "| # | Problem | Difficulty | Tags | Sheets | Status |", "|---|---|---|---|---|---|"]
    lines += [row(n, link_to(n, page_dir), ", ".join(n.tags), " ".join(sheets.get(n.number, [])) or "—")
              for n in here]
    if elsewhere:
        lines += ["", f"### Same pattern, filed elsewhere ({len(elsewhere)})", "",
                  "| # | Problem | Difficulty | Folder | Status |", "|---|---|---|---|---|"]
        lines += [row(n, link_to(n, page_dir), n.folder.replace("_", " ")) for n in elsewhere]
    lines += ["", LADDER_END]
    return "\n".join(lines)


def new_page(folder):
    spec = taxonomy()["folders"][folder]
    return f"# {spec['title']}\n\n{spec.get('summary', '')}\n\n{LADDER_START}\n{LADDER_END}\n"


def page_text(folder, notes, current=None):
    text = current if current is not None else new_page(folder)
    i, j = text.find(LADDER_START), text.find(LADDER_END)
    if i == -1 or j == -1:
        text = text.rstrip("\n") + f"\n\n{LADDER_START}\n{LADDER_END}\n"
        i, j = text.find(LADDER_START), text.find(LADDER_END)
    return text[:i] + ladder(folder, notes) + text[j + len(LADDER_END):]


def pattern_pages(notes):
    """{README path: expected text} for every folder that has notes."""
    out = {}
    for folder in sorted({n.folder for n in notes}):
        path = REPO / folder / "README.md"
        current = path.read_text(encoding="utf-8").replace("\r\n", "\n") if path.exists() else None
        out[path] = page_text(folder, notes, current)
    return out


def companies():
    return json.loads(COMPANIES_FILE.read_text(encoding="utf-8")) if COMPANIES_FILE.exists() else None


def company_slugs(name, data=None):
    """Slugs asked at the company whose name contains `name` (case-insensitive): its top list + last 6 months."""
    data = data or companies()
    if not data:
        raise SystemExit("tools/companies.json is missing: run tools/refresh_companies.py")
    hits = [c for c in data["companies"] if name.lower() in c.lower()]
    exact = [c for c in hits if c.lower() == name.lower()]
    hits = exact or hits
    if len(hits) != 1:
        raise SystemExit(f"--company {name!r} matches {hits or 'no company'}; see COMPANIES.md")
    entry = data["companies"][hits[0]]
    return set(entry["all"]) | set(entry["recent"])


def render_companies(notes):
    data = companies()
    if not data:
        return None
    by_slug = {n.slug: n for n in notes}
    titles = data["titles"]
    lines = ["# Companies", "", f"Generated by `python tools/build_index.py` from `tools/companies.json` "
             f"(source: {data['source']}, as of {data['as_of']}; refresh with `tools/refresh_companies.py`). "
             "Frequency lists are reported by candidates and age quickly: check the date.", "",
             "Practise one company: `python tools/review.py today --company google`.", "",
             f"| Company | Top problems | In this repo | ✅ | Asked in the last 6 months | In this repo |",
             "|---|---|---|---|---|---|"]
    for name, entry in data["companies"].items():
        top = entry["all"]
        here = [by_slug[s] for s in top if s in by_slug]
        recent_here = sum(1 for s in entry["recent"] if s in by_slug)
        anchor = name.lower().replace(" ", "-").replace(".", "")
        lines.append(f"| [{name}](#{anchor}) | {len(top)} | {len(here)} | {sum(1 for n in here if n.status == '✅')} "
                     f"| {len(entry['recent'])} | {recent_here} |")
    for name, entry in data["companies"].items():
        recent = set(entry["recent"])
        lines += ["", f"## {name}", "", f"Top {min(COMPANY_TOP, len(entry['all']))} by frequency (🕒 = asked in the "
                  "last 6 months):", "", "| Rank | Problem | Difficulty | Status |", "|---|---|---|---|"]
        for rank, slug in enumerate(entry["all"][:COMPANY_TOP], 1):
            mark = " 🕒" if slug in recent else ""
            note = by_slug.get(slug)
            if note:
                lines.append(f"| {rank} | [{note.number}. {note.title}]({link_to(note)}){mark} | {note.difficulty} "
                             f"| {note.status} |")
            else:
                title, difficulty = titles.get(slug, [slug, "?"])
                lines.append(f"| {rank} | {title} ([LeetCode](https://leetcode.com/problems/{slug}/)){mark} "
                             f"| {difficulty} | *not in this repo* |")
    return "\n".join(lines) + "\n"
